# Writes `lib/trinity/n6/unicode15.ex`, the four tables the N6 text rule reads (slice 142; N6 draft
# v0.1-r7 section 2.4), from the Unicode 15.0.0 data files in the directory given:
#
#     elixir scripts/unicode15_tables.exs <ucd dir> lib/trinity/n6/unicode15.ex
#
# The directory holds the three files as published at https://www.unicode.org/Public/15.0.0/ucd/
# (DerivedGeneralCategory.txt is under extracted/ there). Each is checked against the SHA-256 below
# before it is read, so the tables can only come from those bytes. The runtime's own Unicode data is
# never consulted: the profile pins 15.0.0 because runtimes ship different versions.
#
# The output is formatted here, so running the script twice writes the same bytes and `mix format`
# leaves the file alone.

defmodule Unicode15Tables do
  @sources [
    {"DerivedGeneralCategory.txt", "fe29a45c0882500e591140aaa5c4f5067e6a5d746806148af34400c48b9c06f9"},
    {"DerivedNormalizationProps.txt",
     "d5687a48c95c7d6e1ec59cb29c0f2e8b052018eb069a4371b7368d0561e12a29"},
    {"UnicodeData.txt", "806e9aed65037197f1ec85e12be6e8cd870fc5608b4de0fffd990f689f376a73"}
  ]

  def main([dir, out]) do
    files =
      Map.new(@sources, fn {name, sha} ->
        bytes = File.read!(Path.join(dir, name))
        got = :crypto.hash(:sha256, bytes) |> Base.encode16(case: :lower)
        got == sha || raise "#{name}: sha256 #{got}, expected #{sha}"
        {name, bytes}
      end)

    gc = files["DerivedGeneralCategory.txt"]
    qc = files["DerivedNormalizationProps.txt"]

    tables = %{
      cn: merge(property(gc, &(&1 == ["Cn"]))),
      cf: merge(property(gc, &(&1 == ["Cf"]))),
      qc_no: merge(property(qc, &(&1 == ["NFC_QC", "N"]))),
      qc_maybe: merge(property(qc, &(&1 == ["NFC_QC", "M"]))),
      ccc: ccc(files["UnicodeData.txt"])
    }

    File.write!(out, source(tables))
  end

  # `{first, last}` for every line whose fields after the code point match.
  defp property(text, match?) do
    for line <- String.split(text, "\n"),
        [data | _] = String.split(line, "#", parts: 2),
        [cps | fields] = data |> String.split(";") |> Enum.map(&String.trim/1),
        cps != "",
        match?.(fields) do
      case String.split(cps, "..") do
        [a] -> {hex(a), hex(a)}
        [a, b] -> {hex(a), hex(b)}
      end
    end
  end

  # Adjacent and overlapping ranges joined, sorted by first code point.
  defp merge(ranges) do
    ranges
    |> Enum.sort()
    |> Enum.reduce([], fn
      {a, b}, [{pa, pb} | rest] when a <= pb + 1 -> [{pa, max(b, pb)} | rest]
      r, acc -> [r | acc]
    end)
    |> Enum.reverse()
  end

  # `{first, last, ccc}` for every run of consecutive code points with the same non-zero class.
  # UnicodeData.txt lists every code point with a non-zero class on its own line.
  defp ccc(text) do
    text
    |> String.split("\n", trim: true)
    |> Enum.map(&String.split(&1, ";"))
    |> Enum.flat_map(fn [cp, _name, _gc, ccc | _] ->
      if ccc == "0", do: [], else: [{hex(cp), String.to_integer(ccc)}]
    end)
    |> Enum.sort()
    |> Enum.reduce([], fn
      {cp, c}, [{a, b, c} | rest] when cp == b + 1 -> [{a, cp, c} | rest]
      {cp, c}, acc -> [{cp, cp, c} | acc]
    end)
    |> Enum.reverse()
  end

  defp hex(s), do: String.to_integer(s, 16)

  defp count(ranges), do: Enum.reduce(ranges, 0, fn r, n -> n + elem(r, 1) - elem(r, 0) + 1 end)

  # The tuples are flat, so the lookup is one binary search over `elem/2`. Code points are written
  # in hex, as Unicode writes them; a combining class (the third element of a `ccc` record) in
  # decimal.
  defp flat(ranges, width \\ 2) do
    items =
      ranges
      |> Enum.flat_map(&Tuple.to_list/1)
      |> Enum.with_index()
      |> Enum.map_join(", ", fn {n, i} ->
        if rem(i, width) == 2, do: Integer.to_string(n), else: hex_literal(n)
      end)

    "{" <> items <> "}"
  end

  defp hex_literal(n), do: "0x" <> String.pad_leading(Integer.to_string(n, 16), 4, "0")

  defp source(t) do
    sources = Enum.map_join(@sources, "\n", fn {name, sha} -> "    * `#{name}`: `#{sha}`" end)

    """
    # SPDX-FileCopyrightText: Sudo Apt Holdings LLC
    # SPDX-FileCopyrightText: Unicode, Inc.
    # SPDX-License-Identifier: Apache-2.0 AND Unicode-3.0
    #
    # Generated by scripts/unicode15_tables.exs from the Unicode 15.0.0 data files. Do not edit.
    defmodule Trinity.N6.Unicode15 do
      @moduledoc \"\"\"
      The four Unicode 15.0.0 tables the N6 text rule reads (N6 draft v0.1-r7 section 2.4; slice
      142): General_Category Cn and Cf, the canonical combining class, and NFC_Quick_Check No and
      Maybe. Generated from these files, checked by SHA-256 before they were read:

    #{sources}

      The runtime's Unicode data is never consulted, because the profile pins one version and
      runtimes ship others. Raising the version is a profile change.
      \"\"\"

      @cn #{flat(t.cn)}
      @cf #{flat(t.cf)}
      @qc_no #{flat(t.qc_no)}
      @qc_maybe #{flat(t.qc_maybe)}
      @ccc #{flat(t.ccc, 3)}

      @doc "The Unicode version of the tables."
      @spec version() :: String.t()
      def version, do: "15.0.0"

      @doc "Code points per table, as the generator counted them."
      @spec counts() :: %{atom() => non_neg_integer()}
      def counts,
        do: %{
          cn: #{count(t.cn)},
          cf: #{count(t.cf)},
          qc_no: #{count(t.qc_no)},
          qc_maybe: #{count(t.qc_maybe)},
          ccc_nonzero: #{count(t.ccc)}
        }

      @doc "General_Category is Cn (unassigned, noncharacters included)."
      @spec unassigned?(non_neg_integer()) :: boolean()
      def unassigned?(cp), do: in_ranges?(@cn, cp)

      @doc "General_Category is Cf (format controls)."
      @spec format_control?(non_neg_integer()) :: boolean()
      def format_control?(cp), do: in_ranges?(@cf, cp)

      @doc "NFC_Quick_Check: `:yes`, `:no` or `:maybe`."
      @spec nfc_qc(non_neg_integer()) :: :yes | :no | :maybe
      def nfc_qc(cp) do
        cond do
          in_ranges?(@qc_no, cp) -> :no
          in_ranges?(@qc_maybe, cp) -> :maybe
          true -> :yes
        end
      end

      @doc "The canonical combining class."
      @spec ccc(non_neg_integer()) :: 0..254
      def ccc(cp) do
        case find(@ccc, 3, cp) do
          nil -> 0
          i -> elem(@ccc, i * 3 + 2)
        end
      end

      defp in_ranges?(table, cp), do: find(table, 2, cp) != nil

      # The index of the range holding `cp` in a flat tuple of `width`-wide records sorted by their
      # first element, or nil.
      defp find(table, width, cp), do: search(table, width, cp, 0, div(tuple_size(table), width) - 1)

      defp search(_table, _width, _cp, lo, hi) when lo > hi, do: nil

      defp search(table, width, cp, lo, hi) do
        mid = div(lo + hi, 2)
        first = elem(table, mid * width)
        last = elem(table, mid * width + 1)

        cond do
          cp < first -> search(table, width, cp, lo, mid - 1)
          cp > last -> search(table, width, cp, mid + 1, hi)
          true -> mid
        end
      end
    end
    """
    |> Code.format_string!()
    |> IO.iodata_to_binary()
    |> Kernel.<>("\n")
  end
end

Unicode15Tables.main(System.argv())
