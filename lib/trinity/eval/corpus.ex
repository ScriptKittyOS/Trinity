defmodule Trinity.Eval.Corpus do
  @moduledoc """
  The memory-recall eval's corpus and queries (slice 133, AC14), generated from a seed.

  The answer sheet's design: memories in fixed proportions (persona facts 25 %, preferences 25 %,
  decisions with their rationale 20 %, facts an observer took from a session 30 %), one to three
  sentences each; corpora of 10^2, 10^3 and 10^4 memories, each a superset of the smaller, the
  larger ones padded with realistic distractors (near-duplicates, the same entity with another
  attribute, older decisions a newer one contradicts); 300 queries, 40 % paraphrases with little
  lexical overlap, 30 % keyword-like, 20 % multi-hop, 10 % with no answer; each query generated
  from the one to three memories that answer it.

  **Generated by templates, not by a model.** The answer sheet asks for the owner's hosted
  frontier-class model; slice 133's NOTES (decision 13) say why it was not loaded here. Every
  query's targets are in the 10^2 core, so each query is answerable at every size and only the
  distractors grow. Everything is a function of the seed: the same seed gives the same bytes,
  which `generation.json` records with each file's SHA-256.

  The memory ids are `m00001` to `m10000`; the core is `m00001` to `m00100`.
  """

  @sizes [100, 1_000, 10_000]

  @typedoc "A memory: id, kind, text, and the smallest corpus size that holds it."
  @type memory :: %{id: String.t(), kind: String.t(), text: String.t(), size: pos_integer()}

  @typedoc "A query: id, kind, text, and the memories that answer it (none for no-answer)."
  @type query :: %{id: String.t(), kind: String.t(), text: String.t(), targets: [String.t()]}

  # Pools. Small on purpose: the distractors reuse them, which is what makes them distractors.
  @women ~w(Anna Dara Elif Greta Ines Keiko Maya Nadia Priya Sana Uma Wen Yara Zoe)
  @men ~w(Bruno Chen Farid Hugo Jonas Luca Omar Rafael Tomas Viktor)
  @people @women ++ @men
  @cities ~w(Lisbon Boston Porto Kyoto Nairobi Oslo Montreal Seville Tbilisi Hanoi Lyon Denver
             Valparaiso Krakow Adelaide Ghent)
  @pet_names ~w(Rex Miso Pepper Biscuit Olive Juno Nacho Ziggy Mochi Basil)
  @tools [
    {"Neovim", "a terminal text editor"},
    {"Postgres", "a relational database"},
    {"SQLite", "an embedded database"},
    {"Kubernetes", "a container orchestrator"},
    {"Obsidian", "a note-taking app"},
    {"a paper notebook", "pen and paper"}
  ]
  @preferences [
    {"oat milk in coffee", "What goes into my morning cup instead of dairy?"},
    {"green tea in the afternoon", "Which hot drink do I have after lunch?"},
    {"short answers with bullet points", "How long should replies to me be?"},
    {"code examples in Elixir", "Which functional language should samples use?"},
    {"metric units", "Kilos or pounds when you give me measurements?"},
    {"British spelling", "Colour or color in my documents?"},
    {"no emoji in replies", "Should messages to me include little pictures?"},
    {"meetings before noon", "When in the day do I like appointments?"},
    {"Neovim for editing", "Which text editor do I use?"},
    {"a paper notebook for planning", "Where do I sketch out my week?"},
    {"window seats on flights", "Aisle or window when I travel by plane?"},
    {"trains over planes for short trips", "How do I like to travel between nearby cities?"},
    {"jazz while working", "What music helps me concentrate?"},
    {"dark mode in every app", "Light or dark themes for me?"},
    {"email over phone calls", "How do I like to be contacted?"},
    {"spicy food", "Do I enjoy a lot of chilli heat?"},
    {"cold showers in the morning", "How do I wake myself up?"},
    {"aisle seats at the cinema", "Where do I sit for a film?"},
    {"reading on paper rather than screens", "Do I like ebooks?"},
    {"a standing desk", "Do I sit while working?"},
    {"quiet cafes for deep work", "Where do I go to focus away from home?"},
    {"weekly summaries on Fridays", "When do I want a recap of the week?"},
    {"plain language without jargon", "How technical should explanations to me be?"},
    {"cycling to work", "How do I commute?"},
    {"sourdough bread from the corner bakery", "Which loaf do I buy?"}
  ]
  @stopwords ~w(a an the in on at for with over than rather from to of)

  # Twenty projects, one decision each, so no two core decisions answer the same question.
  @projects ~w(analytics billing onboarding garden-planner thesis kitchen-renovation podcast
               wedding move-abroad marathon-training newsletter tax-return photo-archive
               choir-website bike-repair language-course family-reunion home-network
               book-club fundraiser)
  @reasons [
    "because it handles concurrent writes",
    "because the budget was tight",
    "because the team already knows it",
    "because the deadline moved up",
    "because the first option kept failing",
    "because it works offline"
  ]
  @events [
    "the outage last week",
    "the call with the landlord",
    "the review meeting",
    "the doctor's appointment",
    "the trip to the coast",
    "the budget discussion"
  ]
  @absent ~w(horse saxophone yacht Reykjavik submarine glacier harpsichord falconry kayak
             observatory)

  @doc "The corpus sizes, smallest first; each is a superset of the one before."
  @spec sizes() :: [pos_integer()]
  def sizes, do: @sizes

  @doc """
  Generates the corpus and the queries from a seed. Returns `%{memories: [memory], queries:
  [query]}`, memories in id order, queries in id order.
  """
  @spec generate(integer()) :: %{memories: [memory()], queries: [query()]}
  def generate(seed) do
    :rand.seed(:exsss, {seed, 133, 14})
    core = core_memories()
    queries = queries(core)
    distractors = distractors(core, 10_000 - length(core))

    memories =
      (core ++ distractors)
      |> Enum.with_index(1)
      |> Enum.map(fn {m, i} ->
        Map.merge(m, %{id: id(i), size: Enum.find(@sizes, &(i <= &1))})
      end)

    # Queries were built against the core's positions; give them the ids now.
    ids = Map.new(Enum.with_index(core, 1), fn {m, i} -> {m.ref, id(i)} end)

    queries =
      queries
      |> Enum.with_index(1)
      |> Enum.map(fn {q, i} ->
        %{id: "q" <> pad(i, 3), kind: q.kind, text: q.text, targets: Enum.map(q.refs, &ids[&1])}
      end)

    %{memories: Enum.map(memories, &Map.delete(&1, :ref)), queries: queries}
  end

  defp id(i), do: "m" <> pad(i, 5)
  defp pad(i, n), do: i |> Integer.to_string() |> String.pad_leading(n, "0")
  defp pick(list), do: Enum.at(list, :rand.uniform(length(list)) - 1)

  ## The core: 100 memories, 25 / 25 / 20 / 30, each carrying what its queries need

  defp core_memories do
    facts = for i <- 1..25, do: persona_fact(i)
    prefs = for i <- 1..25, do: preference(i)
    {decisions, events} = for(i <- 1..20, do: decision_pair(i)) |> Enum.unzip()
    observed = events ++ for(i <- 1..10, do: observed_fact(i))
    facts ++ prefs ++ decisions ++ observed
  end

  # Persona facts: 25 distinct slots, so no paraphrase can be answered by two core memories.
  # Each slot is {template, paraphrase, second paraphrase, keyword}, the paraphrases sharing as
  # few content words with the memory as the slot allows.
  defp persona_fact(i) do
    city = pick(@cities)

    who =
      if i in [2, 4],
        do: pick(@men),
        else: if(i in [1, 3, 8], do: pick(@women), else: pick(@people))

    year = 2015 + :rand.uniform(10)
    name = pick(@pet_names)

    birthplace = pick(@cities)

    {text, para, para2, keyword} =
      Enum.at(
        [
          {"The person's sister #{who} lives in #{city}.",
           "Which town is my female sibling based in?", "Where is #{who}'s home these days?",
           "sister #{city}"},
          {"The person's brother #{who} lives in #{city}.",
           "In which place has my male sibling settled?", "Where does #{who} stay?",
           "brother #{city}"},
          {"The person's mother #{who} lives in #{city}.", "Where is mum's house?",
           "Which town is my mom in?", "mother #{city}"},
          {"The person's father #{who} retired to #{city}.",
           "Where did dad go after he stopped working?", "Which place is my old man in now?",
           "father retired #{city}"},
          {"The person's partner is called #{who}.", "What is my significant other's name?",
           "Who am I in a relationship with?", "partner #{who}"},
          {"The person's best friend #{who} is a pilot.", "What job does my closest pal have?",
           "Who flies planes among my friends?", "best friend pilot"},
          {"The person's manager is #{who}.", "Who is my boss?", "Who do I report to at work?",
           "manager #{who}"},
          {"The person's daughter #{who} started school in #{year}.",
           "When did my child begin her education?", "What year did my kid's classes start?",
           "daughter school #{year}"},
          {"The person has a dog called #{name}.", "What did I name my pup?",
           "What is my hound called?", "dog #{name}"},
          {"The person has a cat called #{name}.", "What is my kitty's name?",
           "What do I call my feline?", "cat #{name}"},
          {"The person works as a backend engineer.", "What do I do for a living?",
           "Remind me of my profession.", "backend engineer"},
          {"The person is allergic to peanuts.", "Which nut gives me a reaction?",
           "Is there a legume I must avoid?", "allergic peanuts"},
          {"The person is allergic to penicillin.", "Which antibiotic is dangerous for me?",
           "Which medicine makes me break out?", "allergic penicillin"},
          {"The person moved to #{city} in #{year}.", "When did I relocate, and to which place?",
           "Which year did I change cities?", "moved #{city} #{year}"},
          {"The person was born in #{birthplace}.", "What is my hometown?",
           "Where did I grow up as a baby?", "born"},
          {"The person's birthday is on the 14th of March.",
           "When should I expect birthday wishes?", "Which day do I turn a year older?",
           "birthday March"},
          {"The person speaks Portuguese and Japanese.", "Which languages can I talk in?",
           "Besides English, what tongues do I know?", "speaks Portuguese Japanese"},
          {"The person drives a blue electric hatchback.", "What kind of car do I have?",
           "Which vehicle is mine?", "electric hatchback"},
          {"The person runs ten kilometres every Sunday.",
           "What exercise routine do I keep at the weekend?", "How far do I jog on Sundays?",
           "runs kilometres Sunday"},
          {"The person plays the cello in a community orchestra.",
           "Which instrument do I perform with?", "What do I play in the amateur ensemble?",
           "cello orchestra"},
          {"The person is vegetarian.", "Do I eat meat?", "What is my diet like?", "vegetarian"},
          {"The person's flat is on the fourth floor without a lift.",
           "How many stairs to my apartment?", "Is there an elevator where I live?",
           "fourth floor lift"},
          {"The person is learning to sail.", "Which water sport am I taking lessons in?",
           "What am I training to do on boats?", "learning sail"},
          {"The person volunteers at a food bank on Saturdays.",
           "Where do I help out at the weekend?", "What charity work do I do?",
           "volunteers food bank"},
          {"The person studied architecture before switching to software.",
           "What was my degree before I changed careers?", "What did I train in originally?",
           "studied architecture"}
        ],
        i - 1
      )

    fact(i, "fact", text, para: para, para2: para2, keyword: keyword)
  end

  # Preferences: 25 distinct slots, as the persona facts are.
  defp preference(i) do
    {thing, para} = Enum.at(@preferences, i - 1)

    fact(100 + i, "preference", "The person prefers #{thing}.",
      para: para,
      keyword: thing |> String.split() |> Enum.reject(&(&1 in @stopwords)) |> Enum.join(" ")
    )
  end

  # A decision and the session event it followed: the pair a multi-hop query needs.
  defp decision_pair(i) do
    project = Enum.at(@projects, rem(i, length(@projects)))
    {tool, _} = pick(@tools)
    reason = pick(@reasons)
    event = pick(@events)

    decision =
      fact(
        200 + i,
        "decision",
        "After #{event}, the person decided to use #{tool} for the #{project} project, #{reason}.",
        para: "Which option did I settle on for the #{project} work, and why?",
        keyword: "#{project} #{tool}"
      )

    happened =
      fact(
        300 + i,
        "observed",
        "In a session about the #{project} project, the person described #{event} and its effect on the plan.",
        para: "What went wrong around the #{project} work that I told you about?",
        keyword: "#{project} #{event}"
      )

    {Map.put(decision, :hop, {project, event, 300 + i}), happened}
  end

  defp observed_fact(i) do
    who = Enum.at(@people, i - 1)
    day = Enum.random(~w(Monday Tuesday Wednesday Thursday Friday))
    project = Enum.at(@projects, i + 9)

    fact(
      400 + i,
      "observed",
      "During a session, the person mentioned that #{who} reviews the #{project} draft every #{day}.",
      para: "Who checks my #{project} writing each week, and on which day?",
      keyword: "#{who} #{project} #{day}"
    )
  end

  defp fact(ref, kind, text, q), do: %{ref: ref, kind: kind, text: text, q: q}

  ## Queries: 120 paraphrases, 90 keyword-like, 60 multi-hop, 30 with no answer

  defp queries(core) do
    # 100 paraphrases, one a core memory, and 20 second phrasings of persona facts.
    seconds = core |> Enum.filter(&Keyword.has_key?(&1.q, :para2)) |> Enum.take(20)
    para = Enum.map(core, &query(&1, :para)) ++ Enum.map(seconds, &query(&1, :para2))

    keyword =
      core |> Enum.shuffle() |> Stream.cycle() |> Enum.take(90) |> Enum.map(&query(&1, :keyword))

    hops = core |> Enum.filter(&Map.has_key?(&1, :hop))

    multi =
      hops
      |> Stream.cycle()
      |> Enum.take(60)
      |> Enum.with_index()
      |> Enum.map(fn {d, n} -> multi_hop(d, n) end)

    none = for n <- 1..30, do: no_answer(n)
    para ++ keyword ++ multi ++ none
  end

  defp query(m, :para), do: %{kind: "paraphrase", text: m.q[:para], refs: [m.ref]}
  defp query(m, :para2), do: %{kind: "paraphrase", text: m.q[:para2], refs: [m.ref]}
  defp query(m, :keyword), do: %{kind: "keyword", text: m.q[:keyword], refs: [m.ref]}

  defp multi_hop(%{ref: ref, hop: {project, event, event_ref}}, n) do
    text =
      case rem(n, 3) do
        0 ->
          "What did I decide about the #{project} project after #{event}?"

        1 ->
          "Once #{event} happened, which way did I go on #{project}?"

        _ ->
          "Tell me what changed in my #{project} plans following #{event}, and the choice I made."
      end

    %{kind: "multi_hop", text: text, refs: [ref, event_ref]}
  end

  # Ten things the corpus never mentions, three phrasings each: thirty distinct questions.
  defp no_answer(n) do
    thing = Enum.at(@absent, rem(n - 1, 10))

    text =
      case div(n - 1, 10) do
        0 -> "What did I name my #{thing}?"
        1 -> "When am I going to #{thing}?"
        _ -> "Remind me what I said about the #{thing}."
      end

    %{kind: "no_answer", text: text, refs: []}
  end

  ## Distractors: near-duplicates, same entity with another attribute, contradicted decisions,
  ## and memories about other people and things

  # A distractor must differ from the memory it imitates in what it says, not only in how: a
  # copy, or a copy with a phrase added, is a second right answer, and recall against one id
  # would count it as a miss. So a near-duplicate swaps an entity (a person, a place, a pet's
  # name, a project, a tool, an event), "same entity, other attribute" changes the relation, and
  # a memory that offers neither becomes an unrelated distractor instead.
  # No two memories in the corpus share a text either: a store whose observer dedupes does not
  # hold the same sentence twice. A distractor that comes out as a text already taken is drawn
  # again (up to ten times), and then made unique by the item it is about.
  defp distractors(core, n) do
    by_kind = Enum.group_by(core, & &1.kind)

    {list, _} =
      Enum.map_reduce(1..n, MapSet.new(core, & &1.text), fn i, taken ->
        kind = kind_for(i)

        text =
          Enum.find_value(1..10, &fresh(by_kind[kind], kind, i, &1, taken)) ||
            "#{pick(@people)} added item #{i} to the #{pick(@projects)} list."

        {%{kind: kind, text: text, ref: nil}, MapSet.put(taken, text)}
      end)

    list
  end

  # The fixed proportions, by position: of every 20 memories, 5 facts, 5 preferences, 4
  # decisions and 6 observed facts (25 %, 25 %, 20 %, 30 %).
  @kind_cycle List.duplicate("fact", 5) ++
                List.duplicate("preference", 5) ++
                List.duplicate("decision", 4) ++ List.duplicate("observed", 6)

  defp kind_for(i), do: Enum.at(@kind_cycle, rem(i - 1, 20))

  defp fresh(pool, kind, i, attempt, taken) do
    m = pick(pool)

    text =
      case rem(i + attempt, 3) do
        0 -> near_duplicate(m.text)
        1 -> other_attribute(m.text)
        2 -> if kind == "decision", do: contradicted(i), else: unrelated(i)
      end

    if is_nil(text) or MapSet.member?(taken, text), do: nil, else: text
  end

  # The same sentence about someone else: shares most of its words with a memory and does not
  # answer that memory's questions. The subject becomes another person ("Omar's sister ...",
  # "Omar decided ..."), and any person, place, pet, project, tool or event named is swapped.
  # nil when nothing could be changed.
  defp near_duplicate(text) do
    who = pick(@people)

    text
    |> String.replace("The person's ", "#{who}'s ", global: false)
    |> String.replace("The person ", "#{who} ", global: false)
    |> String.replace("the person ", "#{who} ", global: false)
    |> swap_entities(text)
  end

  defp swap_entities(text, original) do
    tool_names = Enum.map(@tools, &elem(&1, 0))

    swaps = [
      {@people, pick(@people)},
      {@cities, pick(@cities)},
      {@pet_names, pick(@pet_names)},
      {@projects, pick(@projects)},
      {tool_names, pick(tool_names)},
      {@events, pick(@events)}
    ]

    swapped =
      Enum.reduce(swaps, text, fn {pool, new}, acc ->
        case Enum.find(pool, &String.contains?(acc, &1)) do
          nil -> acc
          ^new -> acc
          old -> String.replace(acc, old, same_kind(old, new))
        end
      end)

    if swapped == original, do: nil, else: swapped
  end

  # A person is swapped for one of the same gender pool, so "sister" stays with a woman's name.
  defp same_kind(old, new) do
    cond do
      old in @women -> pick(@women -- [old])
      old in @men -> pick(@men -- [old])
      true -> new
    end
  end

  # The same entity with another attribute; nil when the sentence has no relation to change.
  @attribute_swaps [
    {"lives in", "works in"},
    {"retired to", "holidays in"},
    {"prefers", "used to prefer"},
    {"is allergic to", "was once tested for"},
    {"decided to use", "considered using"},
    {"has a dog called", "once looked after a dog called"},
    {"has a cat called", "fed a neighbour's cat called"},
    {"works as a", "once interviewed to be a"},
    {"reviews the", "once proofread the"}
  ]

  # Where the sentence also names someone or somewhere, that is swapped too, so the many
  # distractors drawn from one memory do not all read the same.
  defp other_attribute(text) do
    case Enum.find(@attribute_swaps, fn {from, _} -> String.contains?(text, from) end) do
      nil ->
        nil

      {from, to} ->
        changed = String.replace(text, from, to, global: false)
        swap_entities(changed, changed) || changed
    end
  end

  defp contradicted(i) do
    project = pick(@projects)
    {tool, _} = pick(@tools)

    "An older note says the person decided to use #{tool} for the #{project} project, before changing their mind (#{2010 + rem(i, 12)})."
  end

  # Memories about other people and things. Enough combinations that they rarely repeat.
  defp unrelated(i) do
    who = pick(@people)
    other = pick(@people)
    city = pick(@cities)
    project = pick(@projects)
    {tool, _} = pick(@tools)
    day = Enum.random(~w(Monday Tuesday Wednesday Thursday Friday Saturday Sunday))

    case rem(i, 6) do
      0 ->
        "#{who} from #{city} recommended a book about #{project} planning."

      1 ->
        "The person read an article about #{city} and its #{Enum.random(~w(trams markets museums parks bridges))}."

      2 ->
        "In passing, the person said #{who} is busy with their own #{project} project."

      3 ->
        "#{who} and #{other} are meeting in #{city} on #{day}."

      4 ->
        "The person saw a talk about #{tool} that #{who} gave in #{city}."

      _ ->
        "#{who} asked whether the #{project} notes could be shared by #{day}."
    end
  end
end
